// --- Internal Data Mapping (for POST) ---

/**
 * Maps the UI payload (camelCase, internal flags) to the format expected by the backend API (snake_case, strings).
 *
 * API Schema POST: {
 *   "harvest_id": "string",  (REQUIRED - generated by frontend, offline-first)
 *   "worker_name": "string",
 *   "block_id": "string",
 *   "weight_on_delivery": decimal,
 *   "date_of_delivery": "string",
 *   "amount_paid": decimal,
 *   "paid_by": "string"
 * }
 *
 * NOTE: harvest_id MUST be sent on POST - generated by frontend, backend accepts it (offline-first approach)
 *
 * @param {object} payload - The raw payload from the UI or the sync queue.
 * @param {boolean} isUpdate - Whether this is an update operation (includes harvest_id)
 * @returns {object} The API-ready payload.
 */
const mapToApiPayload = (payload, isUpdate = false) => {
    const apiPayload = {};

    // 0. Harvest ID (UI: generatedId/id/harvest_id -> API: harvest_id) - REQUIRED for offline-first
    apiPayload.harvest_id = payload.generatedId || payload.id || payload.harvest_id || '';

    // 1. Worker Name (UI: workerName/worker_name/name -> API: worker_name)
    apiPayload.worker_name = payload.workerName || payload.worker_name || payload.name || '';

    // 2. Block ID (UI: blockId/block_id/block -> API: block_id)
    apiPayload.block_id = payload.blockId || payload.block_id || payload.block || '';

    // 3. Date (UI: date (Date object/ISO string) -> API: date_of_delivery (YYYY-MM-DD string))
    let dateObj = payload.date;
    if (typeof dateObj === 'string') {
        // Convert ISO string (from AsyncStorage) back to a Date object
        dateObj = new Date(dateObj);
    }

    if (dateObj instanceof Date && !isNaN(dateObj)) {
        const year = dateObj.getFullYear();
        const month = String(dateObj.getMonth() + 1).padStart(2, '0');
        const day = String(dateObj.getDate()).padStart(2, '0');
        apiPayload.date_of_delivery = `${year}-${month}-${day}`;
    } else {
        // Fallback for direct date string if parsing failed
        apiPayload.date_of_delivery = payload.date ? payload.date.split('T')[0] : '';
    }

    // 4. Weight (UI: weight (Number) -> API: weight_on_delivery (decimal))
    apiPayload.weight_on_delivery = Number(payload.weight);

    // 5. Amount Paid (UI: amountPaid (Number) -> API: amount_paid (decimal))
    apiPayload.amount_paid = Number(payload.amountPaid || payload.amount_paid || 0);

    // 6. Paid By (UI: paidBy/paid_by/who_paid -> API: paid_by (string))
    if (typeof payload.paidBy === 'object' && payload.paidBy && payload.paidBy.id) {
        apiPayload.paid_by = String(payload.paidBy.id);
    } else if (payload.paidBy) {
        apiPayload.paid_by = String(payload.paidBy);
    } else if (payload.paid_by) {
        apiPayload.paid_by = String(payload.paid_by);
    } else if (payload.who_paid) {
        apiPayload.paid_by = String(payload.who_paid);
    } else {
        apiPayload.paid_by = '';
    }

    return apiPayload;
};

// --- Exported API Functions ---

/**
 * Handles the POST request to create a new Production Harvest record.
 */
export const postProductionHarvestRecord = async (uiPayload) => {
    const apiPayload = mapToApiPayload(uiPayload);
    // Endpoint: harvests/ (production harvests from the harvests app)
    const endpoint = 'harvests/';

    // Debug logging for payload
    console.log('[postProductionHarvestRecord] Original UI payload:', uiPayload);
    console.log('[postProductionHarvestRecord] Mapped API payload:', apiPayload);

    try {
        // Validate API payload before sending (critical check!)
        if (!apiPayload.harvest_id) {
            const errorMsg = 'CRITICAL: harvest_id is empty or missing in API payload. Record cannot be synced without an ID.';
            console.error('[postProductionHarvestRecord] ' + errorMsg);
            console.error('[postProductionHarvestRecord] Payload details:', JSON.stringify(apiPayload, null, 2));
            return {
                success: false,
                status: 400,
                remoteData: errorMsg,
                validationError: true
            };
        }

        const response = await ApiService.post(endpoint, apiPayload);
        console.log('[postProductionHarvestRecord] ✅ Production harvest created successfully with ID:', apiPayload.harvest_id);

        // Log to persistent sync log
        await addSyncLog('productionHarvestService', 'POST', 'SUCCESS',
            `Successfully created harvest ${apiPayload.harvest_id}`,
            { harvest_id: apiPayload.harvest_id, status: response.status }
        );

        // Log activity for successful harvest creation
        try {
            const workerName = apiPayload.worker_name || 'Unknown';
            const weight = apiPayload.weight_on_delivery || 0;
            await logProductionHarvestCreated(response.data.harvest_id || 'N/A', workerName, weight);
        } catch (activityError) {
            console.warn('[postProductionHarvestRecord] Failed to log activity:', activityError);
        }

        return { success: true, status: response.status, remoteData: response.data };
    } catch (error) {
        // Return 0 for status if network error (offline) to handle offline state robustly
        const status = error.response ? error.response.status : 0;
        const remoteData = error.response ? error.response.data : (error.message || 'Network Error');
        const errorMsg = typeof remoteData === 'string' ? remoteData : JSON.stringify(remoteData);

        // Log to persistent sync log for later debugging
        await addSyncLog('productionHarvestService', 'POST', 'ERROR',
            `Failed to create harvest ${apiPayload.harvest_id}`,
            {
                harvest_id: apiPayload.harvest_id,
                status: status,
                error_message: errorMsg.substring(0, 200),
            }
        );

        // Log CRITICAL ERROR with visual separation so it's visible (not buried in HTML)
        console.error('\n\n');
        console.error('╔════════════════════════════════════════════════════════════╗');
        console.error('║ ❌ POST REQUEST FAILED - CRITICAL ERROR                   ║');
        console.error('╠════════════════════════════════════════════════════════════╣');
        console.error(`║ Status Code: ${status}`);
        console.error(`║ Harvest ID: ${apiPayload.harvest_id || 'MISSING'}`);
        console.error(`║ Worker: ${apiPayload.worker_name || 'Unknown'}`);
        console.error('╠════════════════════════════════════════════════════════════╣');
        console.error('║ Error Summary:');
        // Only show first 150 chars to avoid HTML dump
        const shortError = errorMsg.substring(0, 150).replace(/\n/g, ' ');
        console.error(`║ ${shortError}`);
        console.error('╚════════════════════════════════════════════════════════════╝');
        console.error('\n\n');

        // Full details for debugging if needed
        console.error('[postProductionHarvestRecord] Full error details:', {
            harvestId: apiPayload.harvest_id,
            workerName: apiPayload.worker_name,
            status: status,
            endpoint: endpoint
        });

        return { success: false, status: status, remoteData: remoteData };
    }
};

