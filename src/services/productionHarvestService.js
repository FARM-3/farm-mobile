// --- OFFLINE SYNC UTILITIES ---

/**
 * Retrieves all unsynced production harvest records from local storage queue.
 */
export const getUnsyncedProductionRecords = async () => {
    try {
        const raw = await AsyncStorage.getItem(SYNC_QUEUE_KEY);
        const records = raw ? JSON.parse(raw) : [];
        return { success: true, records };
    } catch (error) {
        console.error("Error retrieving unsynced production records:", error);
        return { success: false, records: [] };
    }
};

/**
 * Removes a record from the local queue after a successful sync.
 * @param {string} localId - The unique local ID of the record to remove.
 */
export const removeProductionRecordFromQueue = async (localId) => {
    try {
        const { records: currentQueue } = await getUnsyncedProductionRecords();

        // Filter out the record matching the localId
        const newQueue = currentQueue.filter(record => record.id !== localId);

        await AsyncStorage.setItem(SYNC_QUEUE_KEY, JSON.stringify(newQueue));
        return { success: true, remaining: newQueue.length };

    } catch (error) {
        console.error("Error removing production record from queue:", error);
        return { success: false, remaining: -1 };
    }
};

/**
 * Tries to sync all locally saved production records to the remote API.
 * This is the main function to call when connectivity is restored.
 */
export const syncAllProductionRecords = async () => {
    console.log(`\n╔════════════════════════════════════════════════════════════╗`);
    console.log(`║ STARTING PRODUCTION HARVEST SYNC                          ║`);
    console.log(`╚════════════════════════════════════════════════════════════╝\n`);

    const { success, records } = await getUnsyncedProductionRecords();
    if (!success || records.length === 0) {
        console.log('[syncAllProductionRecords] ℹ️  No records to sync');
        console.log(`\n╔════════════════════════════════════════════════════════════╗`);
        console.log(`║ SYNC SKIPPED - NO PENDING RECORDS                         ║`);
        console.log(`╚════════════════════════════════════════════════════════════╝\n`);
        return { syncedCount: 0, totalCount: 0, failedRecords: [] };
    }

    let syncedCount = 0;
    const totalCount = records.length;
    const failedRecords = [];

    console.log(`[syncAllProductionRecords] Found ${totalCount} record(s) waiting to sync`);
    console.log(`[syncAllProductionRecords] Sync queue contents:`);
    records.forEach((record, index) => {
        console.log(`  ${index + 1}. ID: ${record.id || 'MISSING'} | Worker: ${record.workerName || 'Unknown'}`);
    });

    // Use a deep copy to iterate over, in case the queue is modified during iteration
    for (const record of records) {
        console.log(`[syncAllProductionRecords] Processing record ${record.id}:`, JSON.stringify(record, null, 2));

        // Validate required fields before attempting sync
        const validationErrors = [];

        // Critical: Harvest ID is REQUIRED for all records (either from local id or harvest_id field)
        if (!record.id && !record.harvest_id) {
            validationErrors.push(`Harvest ID is missing (neither id nor harvest_id found)`);
        }

        if (!record.paidBy && !record.paid_by && !record.who_paid) {
            validationErrors.push(`paidBy is missing`);
        }

        if (!record.workerName && !record.worker_name && !record.name) {
            validationErrors.push(`workerName is missing`);
        }

        if (!record.blockId && !record.block_id && !record.block) {
            validationErrors.push(`blockId is missing`);
        }

        if (!record.date) {
            validationErrors.push(`date is missing`);
        }

        if (!record.weight && record.weight !== 0) {
            validationErrors.push(`weight is missing`);
        }

        if (validationErrors.length > 0) {
            console.warn(`[syncAllProductionRecords] Skipping record ${record.id}: ${validationErrors.join(', ')}`);
            failedRecords.push({ id: record.id, reason: validationErrors.join(', ') });
            continue;
        }

        // Try to POST the record. If it already exists (409 or 405), use PUT instead
        console.log(`\n[syncAllProductionRecords] ──────────────────────────────────────────`);
        console.log(`[syncAllProductionRecords] Step 1️⃣: Attempting POST to create new record...`);
        console.log(`[syncAllProductionRecords] Record ID: ${record.id || 'MISSING'}`);
        let response = await postProductionHarvestRecord(record);

        // If POST fails with 405 or 409 (conflict/method not allowed), try PUT (update)
        if (!response.success && (response.status === 405 || response.status === 409)) {
            console.log(`[syncAllProductionRecords] ⚠️  POST failed with status ${response.status} (conflict detected)`);
            console.log(`[syncAllProductionRecords] Step 2️⃣: Record already exists on backend, attempting PUT (update)...`);
            response = await updateProductionHarvestRecord(record.id, record);
        }

        if (response.success) {
            // If successful, remove the record from the local queue
            console.log(`[syncAllProductionRecords] ✅ Step 3️⃣: SYNC SUCCESS - Record ${record.id} synced successfully!`);
            console.log(`[syncAllProductionRecords] Removing from sync queue...`);
            await removeProductionRecordFromQueue(record.id);
            syncedCount++;
            console.log(`[syncAllProductionRecords] ──────────────────────────────────────────\n`);
        } else {
            // Failed (either offline or API issue). Leave it in the queue for the next sync attempt.
            console.error(`[syncAllProductionRecords] ❌ SYNC FAILED for record ${record.id}`);
            console.error(`[syncAllProductionRecords] Status Code: ${response.status}`);
            console.error(`[syncAllProductionRecords] Error Details:`, response.remoteData);
            if (response.validationError) {
                console.error(`[syncAllProductionRecords] ⚠️  VALIDATION ERROR - Check record data integrity`);
            }
            console.error(`[syncAllProductionRecords] Record left in queue for retry`);
            console.log(`[syncAllProductionRecords] ──────────────────────────────────────────\n`);
            failedRecords.push({
                id: record.id,
                status: response.status,
                error: response.remoteData,
                validationError: response.validationError || false
            });
        }
    }

    console.log(`\n╔════════════════════════════════════════════════════════════╗`);
    console.log(`║ SYNC COMPLETE                                              ║`);
    console.log(`╠════════════════════════════════════════════════════════════╣`);
    console.log(`║ Total Records: ${totalCount}`);
    console.log(`║ Successfully Synced: ${syncedCount} ✅`);
    console.log(`║ Failed: ${failedRecords.length} ${failedRecords.length > 0 ? '❌' : ''}`);
    console.log(`╚════════════════════════════════════════════════════════════╝\n`);

    if (failedRecords.length > 0) {
        console.error(`[syncAllProductionRecords] FAILED RECORDS DETAILS:`);
        failedRecords.forEach((record, index) => {
            console.error(`  ${index + 1}. ID: ${record.id}`);
            console.error(`     Status: ${record.status}`);
            if (record.validationError) {
                console.error(`     Issue: VALIDATION ERROR - Payload problem`);
            } else if (record.reason) {
                console.error(`     Reason: ${record.reason}`);
            } else {
                console.error(`     Error: ${typeof record.error === 'string' ? record.error.substring(0, 100) : 'See details above'}`);
            }
        });
    }

    // Log sync completion activity
    if (syncedCount > 0) {
        try {
            await logSyncCompleted(syncedCount, totalCount);
        } catch (activityError) {
            console.warn('[syncAllProductionRecords] Failed to log sync activity:', activityError);
        }
    }

    return { syncedCount, totalCount, failedRecords };
};
